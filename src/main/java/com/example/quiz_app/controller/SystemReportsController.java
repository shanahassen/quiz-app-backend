package com.example.quiz_app.controller;

import com.example.quiz_app.model.AuditLog;
import com.example.quiz_app.dto.SystemReportResponse;
import com.example.quiz_app.service.AuditLogService;
import com.example.quiz_app.service.SystemReportService;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.web.PageableDefault;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.*;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;

@RestController
@RequestMapping("/api/admin")
@RequiredArgsConstructor
@PreAuthorize("hasAuthority('MANAGE_ROLE')")
public class SystemReportsController {

    private final SystemReportService systemReportService;
    private final AuditLogService auditLogService;

    @PostMapping("/system-reports")
    public ResponseEntity<Map<String, Object>> generateReport() {
        String actor = currentUser();

        SystemReportResponse report =
                systemReportService.generateReport(actor);

        auditLogService.logAction(
                actor,
                "GENERATE_REPORT",
                "SYSTEM_REPORT",
                report.refId(),
                "Generated a system summary report"
        );

        return ResponseEntity.ok(Map.of(
                "message", "System report generated successfully.",
                "payload", report
        ));
    }

    @GetMapping("/system-reports")
    public ResponseEntity<Map<String, Object>> getReports(
            @PageableDefault(size = 10) Pageable pageable) {
        Page<SystemReportResponse> reports =
                systemReportService.getAllReports(pageable);

        return ResponseEntity.ok(Map.of(
                "message", "System reports retrieved successfully.",
                "payload", reports.getContent(),
                "totalElements", reports.getTotalElements()
        ));
    }

    @GetMapping("/system-reports/{refId}")
    public ResponseEntity<Map<String, Object>> getReport(
            @PathVariable String refId) {

        return ResponseEntity.ok(Map.of(
                "message", "System report retrieved successfully.",
                "payload", systemReportService.getReport(refId)
        ));
    }

    @GetMapping("/system-reports/{refId}/download")
    public ResponseEntity<byte[]> downloadReport(
            @PathVariable String refId) {

        SystemReportResponse report =
                systemReportService.getReport(refId);

        StringBuilder csv = new StringBuilder();
        csv.append("Report Name,")
                .append(escapeCsv(report.reportName()))
                .append("\n");

        csv.append("Generated By,")
                .append(escapeCsv(report.generatedBy()))
                .append("\n");

        csv.append("Generated At,")
                .append(report.generatedAt())
                .append("\n\n");

        csv.append("Metric,Count\n");

        report.summary().forEach((metric, count) ->
                csv.append(escapeCsv(metric))
                        .append(",")
                        .append(count)
                        .append("\n")
        );

        return csvResponse(
                csv.toString(),
                "system-report-" + refId + ".csv"
        );
    }

    @GetMapping("/audit-logs")
    public ResponseEntity<Map<String, Object>> getAuditLogs(
            @PageableDefault(size = 10) Pageable pageable) {
        Page<AuditLog> logs = auditLogService.getAllLogs(pageable);

        return ResponseEntity.ok(Map.of(
                "message", "Audit logs retrieved successfully.",
                "payload", logs.getContent(),
                "totalElements", logs.getTotalElements()
        ));
    }

    @GetMapping("/audit-logs/download")
    public ResponseEntity<byte[]> downloadAuditLogs() {
        List<AuditLog> logs = auditLogService.getAllLogs();

        StringBuilder csv = new StringBuilder();
        csv.append("Timestamp,Actor,Action,Entity Type,Entity Ref ID,Description\n");

        for (AuditLog log : logs) {
            csv.append(escapeCsv(log.getTimestamp()))
                    .append(",")
                    .append(escapeCsv(log.getActorEmail()))
                    .append(",")
                    .append(escapeCsv(log.getAction()))
                    .append(",")
                    .append(escapeCsv(log.getEntityType()))
                    .append(",")
                    .append(escapeCsv(log.getEntityRefId()))
                    .append(",")
                    .append(escapeCsv(log.getDescription()))
                    .append("\n");
        }

        return csvResponse(csv.toString(), "qube-audit-logs.csv");
    }

    private String currentUser() {
        var authentication = org.springframework.security.core.context
                .SecurityContextHolder.getContext().getAuthentication();

        return authentication == null
                ? "UNKNOWN"
                : authentication.getName();
    }

    private String escapeCsv(Object value) {
        String text = value == null ? "" : value.toString();
        return "\"" + text.replace("\"", "\"\"") + "\"";
    }

    private ResponseEntity<byte[]> csvResponse(
            String content,
            String filename) {

        return ResponseEntity.ok()
                .contentType(new MediaType(
                        "text", "csv", StandardCharsets.UTF_8))
                .header(
                        HttpHeaders.CONTENT_DISPOSITION,
                        "attachment; filename=\"" + filename + "\""
                )
                .body(content.getBytes(StandardCharsets.UTF_8));
    }
}